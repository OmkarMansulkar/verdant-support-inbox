"""Customer view API: /api/customer/*. A test tool, no sign-in (as the brief asks).

Sending: the browser's message is turned into a webhook event, signed here
with the webhook secret, and passed to the same handle_webhook() that
POST /webhook uses. Signature check, validation, idempotency, storage and
drafting are therefore literally the same code. The secret never reaches
the browser.

Reading: only the `messages` table is queried. Drafts live in their own
table, so they can't reach the Customer view without someone deliberately
adding a join here (D11). Agent rows in `messages` exist only once an agent
has approved a reply.

Abuse limits: requests are limited per IP (rate_limit.py). A picked test
customer always gets the name and phone defined here, and a typed customer
gets an id starting with `web_` (keyed by phone), so this public endpoint
can't rename or write into a customer the chat platform created.
"""

import json
import re
from datetime import datetime, timezone
from typing import Annotated
from uuid import UUID

from fastapi import APIRouter, BackgroundTasks, Depends, HTTPException
from fastapi.exceptions import RequestValidationError
from pydantic import BaseModel, BeforeValidator, ConfigDict, Field, ValidationError

from app import db, webhook
from app.config import get_settings
from app.rate_limit import RateLimiter, limit

router = APIRouter(prefix="/api/customer")

BRAND_ID = "verdant-co"  # the Customer view plays customers of the one demo brand

# The test customers offered in the picker. Same people as seed.sql; Aisha
# matches the brief's sample webhook, so webhook tests appear in her thread.
TEST_CUSTOMERS = {
    "cust_1042": {"name": "Aisha Khan", "phone": "+919800000001"},
    "cust_1043": {"name": "Rohan Mehta", "phone": "+919800000002"},
    "cust_1044": {"name": "Meera Iyer", "phone": "+919800000003"},
}

# Sending costs an LLM call; reading is one indexed query, polled every 4 s.
send_limiter = RateLimiter(max_requests=10, window_seconds=60)
read_limiter = RateLimiter(max_requests=60, window_seconds=60)

Text = Annotated[str, BeforeValidator(webhook.reject_nul)]


class SendIn(BaseModel):
    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)
    # Generated by the browser once per message. A double-click or a retry after
    # a timeout reuses it, so the webhook's idempotency turns it into a duplicate.
    client_message_id: UUID
    # Either a test customer from the picker...
    test_customer_id: str | None = None
    # ...or a typed name and phone number.
    name: Annotated[Text, Field(min_length=1, max_length=200)] | None = None
    phone: Annotated[str, Field(min_length=3, max_length=32)] | None = None
    text: Annotated[Text, Field(min_length=1, max_length=4000)]


@router.get("/test-customers", dependencies=[Depends(limit(read_limiter, "customer_read"))])
def list_test_customers() -> list[dict]:
    # Served from this constant, not the database: a public endpoint must not
    # list the brand's real customers.
    return [{"id": customer_id, **details} for customer_id, details in TEST_CUSTOMERS.items()]


@router.post("/messages", dependencies=[Depends(limit(send_limiter, "customer_send"))])
def send_message(
    background_tasks: BackgroundTasks,
    # Read with the webhook's 64 KB cap (and only after the rate limit above),
    # instead of letting FastAPI read a body of any size.
    raw_body: bytes = Depends(webhook.read_limited_body),
) -> dict:
    body = _parse(raw_body)
    customer = _customer_for_send(body)

    event = {
        "event_id": f"web_evt_{body.client_message_id}",
        "type": "message.received",
        "brand_id": BRAND_ID,
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "customer": customer,
        "message": {"id": f"web_msg_{body.client_message_id}", "type": "text", "text": body.text},
    }
    raw_event = json.dumps(event).encode()
    signature = webhook.sign(raw_event, get_settings().webhook_secret)

    # Same function as POST /webhook. It logs the event, and the web_evt_ prefix
    # on the event_id shows in the logs that it came from the Customer view.
    outcome = webhook.handle_webhook(raw_event, signature, background_tasks)
    return {"status": outcome.status, "customer_id": customer["id"]}


@router.get("/conversation", dependencies=[Depends(limit(read_limiter, "customer_read"))])
def get_conversation(test_customer_id: str | None = None, phone: str | None = None) -> dict:
    """The customer's open conversation: their messages and approved agent replies."""
    if test_customer_id:
        customer_id = _check_test_customer(test_customer_id)
    else:
        customer_id = f"web_{_phone_digits(phone)}"
    with db.connection() as conn:
        messages = conn.execute(
            """
            select m.id, m.sender, m.body, m.created_at
            from messages m
            join conversations cv on cv.id = m.conversation_id
            join customers c on c.id = cv.customer_id
            where c.brand_id = %s and c.external_id = %s and cv.status = 'open'
            order by m.created_at, m.id
            """,
            (BRAND_ID, customer_id),
        ).fetchall()
    # An unknown customer simply has no messages yet (no 404, which would
    # also tell a stranger which phone numbers have written to the brand).
    return {"customer_id": customer_id, "messages": messages}


def _parse(raw_body: bytes) -> SendIn:
    try:
        return SendIn.model_validate_json(raw_body)
    except ValidationError as error:
        # FastAPI's own handler turns this into its usual 422 response.
        raise RequestValidationError(error.errors(include_input=False, include_url=False))


def _customer_for_send(body: SendIn) -> dict:
    """Webhook-shaped customer fields for a picked test customer or a typed one."""
    if body.test_customer_id:
        customer_id = _check_test_customer(body.test_customer_id)
        return {"id": customer_id, **TEST_CUSTOMERS[customer_id]}
    digits = _phone_digits(body.phone)
    if not body.name:
        raise HTTPException(422, "Enter a name")
    # Keyed by the digits, so "+91 98000 00004" and "+919800000004" are the same person.
    return {"id": f"web_{digits}", "name": body.name, "phone": "+" + digits}


def _check_test_customer(customer_id: str) -> str:
    if customer_id not in TEST_CUSTOMERS:
        raise HTTPException(422, "Unknown test customer")
    return customer_id


def _phone_digits(phone: str | None) -> str:
    digits = re.sub(r"[\s\-().]", "", phone or "").removeprefix("+")
    if not (digits.isascii() and digits.isdigit() and 8 <= len(digits) <= 15):
        raise HTTPException(422, "Enter a phone number with 8 to 15 digits, e.g. +91 98000 00004")
    return digits
